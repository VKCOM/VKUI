import * as fs from 'node:fs';
import * as path from 'node:path';
import remarkFrontmatter from 'remark-frontmatter';
import remarkMdx from 'remark-mdx';
import remarkParse from 'remark-parse';
import { unified } from 'unified';
import { visit } from 'unist-util-visit';
import { compilePreview, vkuiExportNames } from './common/compilePreview.ts';
import { getPreviewId } from './common/previewId.mjs';
import { runIfMain } from './common/runIfMain.ts';
import { generateShowcaseData } from './generate-showcase.ts';

const website = path.resolve(import.meta.dirname, '..');
const output = path.join(website, 'generated');
const parser = unified().use(remarkParse).use(remarkFrontmatter).use(remarkMdx);
const cache = new Map<string, { body: string; codes: string[] }>();
const compiled = new Set<string>();
let pending: Promise<void> | undefined;

function writeChanged(filename: string, contents: string) {
  if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== contents) {
    fs.writeFileSync(filename, contents);
  }
}

async function generate() {
  fs.mkdirSync(path.join(output, 'previews'), { recursive: true });
  const examples = new Map<string, { code: string; filename: string }>();
  const content = path.join(website, 'content');
  for (const relative of fs
    .readdirSync(content, { recursive: true, encoding: 'utf8' })
    .filter((name) => name.endsWith('.mdx'))
    .sort()) {
    const filename = path.join(content, relative);
    const body = fs.readFileSync(filename, 'utf8');
    let entry = cache.get(filename);
    if (entry?.body !== body) {
      const codes: string[] = [];
      visit(parser.parse(body), 'mdxJsxFlowElement', (node) => {
        if (node.name === 'Playground') {
          visit(node, 'code', (code) => {
            codes.push(code.value);
          });
        }
      });
      entry = { body, codes };
      cache.set(filename, entry);
    }
    for (const code of entry.codes) {
      examples.set(getPreviewId(code), { code, filename });
    }
  }

  for (const [id, { code, filename: sourceFile }] of examples) {
    const filename = path.join(output, 'previews', `${id}.js`);
    // Recompile on each process start; subsequent dev compilations reuse identical examples.
    if (!fs.existsSync(filename) || !compiled.has(id)) {
      try {
        writeChanged(filename, compilePreview(code));
      } catch (cause) {
        throw new Error(`Could not compile Playground in ${sourceFile}: ${String(cause)}`);
      }
      compiled.add(id);
    }
  }
  const groups = new Map<string, string[]>();
  const indexes: Record<string, string> = {};
  fs.mkdirSync(path.join(output, 'previews', 'groups'), { recursive: true });
  for (const [id, { filename }] of examples) {
    const group = getPreviewId(path.relative(content, filename));
    const ids = groups.get(group) || [];
    ids.push(id);
    groups.set(group, ids);
    indexes[id] = group;
  }
  for (const [group, ids] of groups) {
    writeChanged(
      path.join(output, 'previews', 'groups', `${group}.js`),
      ids
        .sort()
        .map((id) => `export { default as Preview_${id} } from '../${id}.js';`)
        .join('\n'),
    );
  }
  writeChanged(
    path.join(output, 'previews.ts'),
    `// Generated by scripts/generate-previews.ts\nimport { lazy, type ComponentType } from 'react';\nconst groups: Record<string, () => Promise<Record<string, ComponentType>>> = {\n${[
      ...groups.keys(),
    ]
      .sort()
      .map((id) => `  '${id}': () => import('./previews/groups/${id}.js'),`)
      .join(
        '\n',
      )}\n};\nconst indexes = ${JSON.stringify(indexes)};\nexport const previews: Record<string, ComponentType> = Object.fromEntries(Object.entries(indexes).map(([id, group]) => [id, lazy(() => groups[group]().then(module => ({ default: module['Preview_' + id] })))]));\n`,
  );
  writeChanged(path.join(output, 'vkui-export-names.json'), JSON.stringify(vkuiExportNames));
  writeChanged(path.join(output, 'preview-ids.json'), JSON.stringify([...examples.keys()]));
  await generateShowcaseData({ silent: true });
}

export function generatePreviews() {
  pending ||= generate().finally(() => {
    pending = undefined;
  });
  return pending;
}

void runIfMain(import.meta.url, generatePreviews);
